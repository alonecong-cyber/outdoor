def _build_categories_meta() -> list[CategoryMeta]:
    """按合并后的 RANKING_ITEMS 动态计算每个品类的 total_count 与 tier_counts。"""
    tier_counts: dict[GearCategory, dict[str, int]] = {
        cat: {"budget": 0, "mid": 0, "flagship": 0} for cat, *_ in _CATEGORY_BASE_META
    }
    for item in RANKING_ITEMS:
        tier_counts[item.category][item.price_tier.value] += 1
    return [
        CategoryMeta(
            id=cat,
            name=name,
            description=description,
            icon_name=icon_name,
            total_count=sum(counts.values()),
            tier_counts=counts,
        )
        for cat, name, description, icon_name in _CATEGORY_BASE_META
        for counts in [tier_counts[cat]]
    ]


CATEGORIES_META: list[CategoryMeta] = _build_categories_meta()
